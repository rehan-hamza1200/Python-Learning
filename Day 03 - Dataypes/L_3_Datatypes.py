# Day 3 - Python Data Types

# String
name = "Rehan Hamza"

# Integer
age = 20

# Float
height = 5.8

# Boolean
is_student = True

# Printing values
print(name)
print(age)
print(height)
print(is_student)

# Checking data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))


#we can perform any operations of datatypes
print (age + 1)
print(height - 20)
print(name + "master")
print(name , "master")
